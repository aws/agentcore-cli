#!/usr/bin/env bun
/**
 * Regenerates src/core/project/migrate/v0CdkApps.ts: what every CLI release that
 * creates v0 projects (v0.4.0 to v0.31.1, 1.0.0-preview.1 to 1.0.0-preview.33)
 * vended in agentcore/cdk, read from its git tag's src/assets/cdk. Releases that
 * vended identical apps share an entry. Run from a clone with the release tags:
 *
 *   bun scripts/generate-v0-cdk-apps.ts
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  dependencyNames,
  manifestFingerprint,
  sourceFingerprint,
} from "../src/core/project/migrate/v0CdkApp";

const REPO_ROOT = join(import.meta.dir, "..");
const OUTPUT = join(REPO_ROOT, "src", "core", "project", "migrate", "v0CdkApps.ts");
const ASSETS = "src/assets/cdk";
/** `agentcore create` renames these templates as it writes them. */
const RENAMED: Record<string, string> = {
  "gitignore.template": ".gitignore",
  "npmignore.template": ".npmignore",
};

const git = (...args: string[]) =>
  execFileSync("git", args, { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

const version = (tag: string) => tag.replace(/^v/, "");
const supported = (tag: string) =>
  /^v0\.\d+\.\d+$/.test(tag) ? Number(tag.split(".")[1]) >= 4 : /^v1\.0\.0-preview\.\d+$/.test(tag);
const tags = git("tag", "-l", "v0.*", "v1.0.0-preview.*")
  .split("\n")
  .filter((tag) => tag && supported(tag))
  .sort((a, b) => {
    const order = (tag: string) =>
      tag.startsWith("v1")
        ? [1, Number(tag.split(".").at(-1))]
        : [0, Number(tag.split(".")[1]), Number(tag.split(".")[2])];
    const [x, y] = [order(a), order(b)];
    for (let i = 0; i < Math.max(x.length, y.length); i++) {
      if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0);
    }
    return 0;
  });

type App = { files: Record<string, string>; packageJson: string };
const apps = new Map<string, { app: App; releases: string[] }>();
const dependencies = new Set<string>();
for (const tag of tags) {
  const files: Record<string, string> = {};
  let packageJson = "";
  for (const path of git("ls-tree", "-r", "--name-only", tag, ASSETS).split("\n").filter(Boolean)) {
    const relative = path.slice(ASSETS.length + 1);
    const file = RENAMED[relative] ?? relative;
    const source = git("show", `${tag}:${path}`);
    if (file === "package.json") {
      const manifest = JSON.parse(source);
      packageJson = manifestFingerprint(manifest);
      for (const name of dependencyNames(manifest)) dependencies.add(name);
    } else {
      files[file] = sourceFingerprint(source);
    }
  }
  const app: App = { files: Object.fromEntries(Object.entries(files).sort()), packageJson };
  const key = JSON.stringify(app);
  const entry = apps.get(key) ?? { app, releases: [] };
  entry.releases.push(version(tag));
  apps.set(key, entry);
}

/** "0.4.0 to 0.15.0 or 1.0.0-preview.1": consecutive releases collapse into ranges. */
function describe(releases: string[]): string {
  const ranges: string[][] = [];
  for (const release of releases) {
    const index = tags.map(version).indexOf(release);
    const last = ranges.at(-1);
    const previous = last?.at(-1);
    if (
      last &&
      previous &&
      tags.map(version).indexOf(previous) === index - 1 &&
      previous.startsWith("1.") === release.startsWith("1.")
    ) {
      last.push(release);
    } else {
      ranges.push([release]);
    }
  }
  return ranges
    .map((range) => (range.length === 1 ? range[0]! : `${range[0]} to ${range.at(-1)}`))
    .join(" or ");
}

const entries = [...apps.values()].map(({ app, releases }) => ({
  releases: describe(releases),
  ...app,
}));
writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-v0-cdk-apps.ts from the release tags. Do not edit.

/** The agentcore/cdk app one or more releases vended: each file's fingerprint, and the manifest's. */
export type V0CdkApp = {
  releases: string;
  /** {@link sourceFingerprint} of each file but package.json, by path relative to agentcore/cdk. */
  files: Record<string, string>;
  /** {@link manifestFingerprint} of package.json. */
  packageJson: string;
};

/** Every app a release that creates v0 projects vended, oldest first. */
export const V0_CDK_APPS: readonly V0CdkApp[] = ${JSON.stringify(entries, null, 2)};

/** Every dependency any of those apps' package.json declared; a v0 deploy may restore any of them. */
export const V0_CDK_DEPENDENCY_NAMES: readonly string[] = ${JSON.stringify([...dependencies].sort(), null, 2)};
`,
);
console.log(`Wrote ${entries.length} apps from ${tags.length} releases to ${OUTPUT}`);
