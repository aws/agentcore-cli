import type { GetOnlineEvaluationConfigResponse } from "@aws-sdk/client-bedrock-agentcore-control";
import type { AppIO } from "../../../io";
import type { CoreOptions } from "../../../core/types";
import type { Core } from "../../types";

export const FAILURE_ANALYSIS = "Builtin.FailureAnalysis";

type InsightSource = Pick<
  GetOnlineEvaluationConfigResponse,
  "evaluators" | "insights" | "dataSourceConfig"
>;

export function usesFailureAnalysis(config: InsightSource): boolean {
  return (
    (config.evaluators ?? []).some((e) => e.evaluatorId === FAILURE_ANALYSIS) ||
    (config.insights ?? []).some((i) => i.insightId === FAILURE_ANALYSIS)
  );
}

// Goes to stderr so --json stdout is unchanged.
export function noteInsights(io: AppIO, config: InsightSource): void {
  if (!usesFailureAnalysis(config)) return;
  const app = config.dataSourceConfig?.cloudWatchLogs?.serviceNames?.[0] ?? "<application-name>";
  io.stderr.write(
    `note: Insights generated by ${FAILURE_ANALYSIS} are not in this output.\n` +
      `      Run: agentcore eval insight list --application-name ${app}\n`,
  );
}

// For commands whose own response lacks the evaluators. The note is advisory, so a
// failed lookup must not fail a command that already succeeded.
export async function noteInsightsForConfig(
  core: Core,
  io: AppIO,
  id: string,
  options: CoreOptions,
): Promise<void> {
  let config: GetOnlineEvaluationConfigResponse;
  try {
    config = await core.eval.getOnlineEvaluationConfig(id, options);
  } catch {
    return;
  }
  noteInsights(io, config);
}
