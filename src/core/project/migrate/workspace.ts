import { rmSync } from "node:fs";
import {
  cp,
  lstat,
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  realpath,
  rm,
  writeFile,
} from "node:fs/promises";
import { constants, tmpdir } from "node:os";
import { basename, dirname, isAbsolute, join, relative, sep } from "node:path";
import { ProjectStateError } from "../../../errors";
import type { FileChange } from "../../../handlers/project/migrate/types";
import type { AssetSource } from "../source";
import { PROJECT_SPEC_RELATIVE_PATH } from "../fsUtils";
import { FsTreeNode } from "../templates/fsTree";

/**
 * Planning builds the v1 project in a temporary copy, so the preview can install,
 * convert, and synthesize for real without changing the user's project.
 */
/**
 * Directories never copied into or compared across a workspace: installed
 * dependencies (npm and Python virtual environments), caches, synth output, and git.
 */
const EXCLUDED_DIRECTORIES = new Set([
  "node_modules",
  ".venv",
  "venv",
  "__pycache__",
  ".pytest_cache",
  "cdk.out",
  ".git",
]);

/** Files and directories never copied: `.env*` holds secrets, and planning doesn't need them. */
const EXCLUDED_NAME = /^\.env/;

function excludedName(name: string): boolean {
  return EXCLUDED_DIRECTORIES.has(name) || EXCLUDED_NAME.test(name);
}

/** Build output of the CDK app, regenerated by its own build; not a change worth listing. */
const IGNORED_IN_CHANGES = ["agentcore/cdk/dist/"];

export type WorkspaceInput = {
  rootPath: string;
  /** The v1 agentcore.json content. */
  spec: unknown;
  /** Converted harnesses: each directory's harness.json is replaced with this harness.yaml. */
  harnesses: { directory: string; yaml: string }[];
  /** Where v1's vended CDK app (`cdk/`) is read from. */
  assetSource: AssetSource;
};

export type MigrationWorkspace = {
  /** The converted copy of the project. */
  directory: string;
  /** How the converted copy differs from the project. */
  changes: FileChange[];
  /** Deletes the workspace. */
  dispose(): Promise<void>;
};

/**
 * Builds the migrated project in a temporary directory, leaving the project itself
 * untouched: a copy of the project (without dependencies, synth output, or git
 * metadata) with v1's agentcore.json, harness.yaml files in place of harness.json,
 * and v1's vended CDK app in place of the v0 one. Dependencies aren't installed.
 */
export async function buildMigrationWorkspace(input: WorkspaceInput): Promise<MigrationWorkspace> {
  const directory = await realpath(await mkdtemp(join(tmpdir(), "agentcore-migrate-")));
  const detach = removeOnInterrupt(directory);
  const dispose = async () => {
    detach();
    await rm(directory, { recursive: true, force: true });
  };
  try {
    // Symlinks are copied as they are rather than rewritten to point back into the
    // project, and every path written below is checked to stay in the workspace, so
    // a symlinked directory can never route a write into the project.
    await cp(input.rootPath, directory, {
      recursive: true,
      verbatimSymlinks: true,
      filter: async (source) => {
        const path = relative(input.rootPath, source);
        if (path === "") return true;
        if (excluded(path)) return false;
        // Sockets, FIFOs, and devices can't be copied and are never project files.
        const stats = await lstat(source);
        return stats.isFile() || stats.isDirectory() || stats.isSymbolicLink();
      },
    });
    const inWorkspace = (...segments: string[]) => insideWorkspace(directory, join(...segments));

    await writeFile(
      await inWorkspace(directory, PROJECT_SPEC_RELATIVE_PATH),
      `${JSON.stringify(input.spec, null, 2)}\n`,
    );
    for (const harness of input.harnesses) {
      const harnessDirectory = await inWorkspace(directory, ...harness.directory.split("/"));
      await mkdir(harnessDirectory, { recursive: true });
      await rm(await inWorkspace(harnessDirectory, "harness.json"), { force: true });
      await writeFile(await inWorkspace(harnessDirectory, "harness.yaml"), harness.yaml);
    }

    const cdkDirectory = await inWorkspace(directory, "agentcore", "cdk");
    await rm(cdkDirectory, { recursive: true, force: true });
    const cdkApp = await FsTreeNode.fromAssetSource(
      { assetSource: input.assetSource },
      { assetDir: "cdk" },
    );
    await cdkApp.write(dirname(cdkDirectory));

    return { directory, changes: await diffTrees(input.rootPath, directory), dispose };
  } catch (error) {
    await dispose();
    throw error;
  }
}

/** Signals that end the process by default, after which the workspace must be gone. */
const TERMINATING_SIGNALS = ["SIGINT", "SIGTERM", "SIGHUP"] as const;

/**
 * Removes the workspace if the process exits, is interrupted, or is terminated
 * before it is disposed, so a Ctrl-C (or a closed terminal, or a `kill`) during a
 * preview leaves no copy of the project behind. Returns the function that
 * detaches the handlers.
 */
export function removeOnInterrupt(directory: string): () => void {
  const remove = () => rmSync(directory, { recursive: true, force: true });
  const handlers = TERMINATING_SIGNALS.map((signal) => {
    const handler = () => {
      detach();
      remove();
      // Listening for a signal replaces Node's default exit; restore it unless
      // something else handles the signal. Windows can only raise SIGINT and SIGTERM
      // on a process, so there the exit is the conventional 128 + signal number.
      if (process.listenerCount(signal) > 0) return;
      if (process.platform === "win32" && signal === "SIGHUP") {
        process.exit(128 + constants.signals.SIGHUP);
      }
      process.kill(process.pid, signal);
    };
    return [signal, handler] as const;
  });
  const detach = () => {
    process.off("exit", remove);
    for (const [signal, handler] of handlers) process.off(signal, handler);
  };
  process.on("exit", remove);
  for (const [signal, handler] of handlers) process.on(signal, handler);
  return detach;
}

/** Compares two directory trees file by file, skipping excluded directories and build output. */
export async function diffTrees(before: string, after: string): Promise<FileChange[]> {
  const [beforeFiles, afterFiles] = await Promise.all([listFiles(before), listFiles(after)]);
  const changes: FileChange[] = [];
  for (const path of new Set([...beforeFiles, ...afterFiles])) {
    if (IGNORED_IN_CHANGES.some((prefix) => path.startsWith(prefix))) continue;
    if (!afterFiles.has(path)) {
      changes.push({ path, kind: "removed" });
    } else if (!beforeFiles.has(path)) {
      changes.push({ path, kind: "added" });
    } else {
      const [a, b] = await Promise.all([readFile(join(before, path)), readFile(join(after, path))]);
      if (!a.equals(b)) changes.push({ path, kind: "modified" });
    }
  }
  return changes.sort((a, b) => a.path.localeCompare(b.path));
}

/**
 * Returns `path` if it resolves inside the workspace once every symlink on the way
 * is followed, and throws otherwise. The deepest existing ancestor is resolved,
 * since the path itself may not exist yet.
 */
async function insideWorkspace(workspace: string, path: string): Promise<string> {
  const resolved = await resolveExisting(path);
  const fromWorkspace = resolved === undefined ? ".." : relative(workspace, resolved);
  if (fromWorkspace === ".." || fromWorkspace.startsWith(`..${sep}`) || isAbsolute(fromWorkspace)) {
    throw new ProjectStateError(
      `Can't build the migrated project: '${relative(workspace, path)}' resolves outside the ` +
        "migration workspace through a symlink. Replace the symlink with the files it points " +
        "to, then try again.",
    );
  }
  return path;
}

/**
 * `path` with every symlink resolved, for a path whose last segments may not exist
 * yet. A dangling symlink on the way resolves to nowhere we can check, so it is
 * reported as outside the workspace (`undefined`).
 */
async function resolveExisting(path: string): Promise<string | undefined> {
  const missing: string[] = [];
  for (let existing = path; ; existing = dirname(existing)) {
    try {
      return join(await realpath(existing), ...missing);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT" || dirname(existing) === existing) {
        throw error;
      }
      const isDanglingLink = await lstat(existing).then(
        (stats) => stats.isSymbolicLink(),
        () => false,
      );
      if (isDanglingLink) return undefined;
      missing.unshift(basename(existing));
    }
  }
}

function excluded(relativePath: string): boolean {
  return relativePath.split(sep).some(excludedName);
}

/** Every regular file under `root`, as `/`-separated relative paths, never entering excluded directories. */
async function listFiles(
  root: string,
  directory = root,
  files = new Set<string>(),
): Promise<Set<string>> {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (excludedName(entry.name)) continue;
    if (entry.isDirectory()) {
      await listFiles(root, path, files);
    } else if (entry.isFile()) {
      files.add(relative(root, path).split(sep).join("/"));
    }
  }
  return files;
}
